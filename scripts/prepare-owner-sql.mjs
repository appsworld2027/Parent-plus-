// Generate the one-copy dashboard upgrade from immutable migration sources.
// This writes a local file only; it never connects to or changes a database.
import { readFile, writeFile } from 'node:fs/promises';
const files = ['202611120002_roster_operations.sql', '202611120003_classes_attendance.sql', '202611120004_attendance_context.sql', '202611120005_observations.sql', '202611140006_fees.sql'];
const header = '-- Generated by npm run prepare:owner-sql. Do not edit this bundle manually.\n'
  + '-- For the existing project with migration 001 already installed. Does not include/rerun 001.\n'
  + '-- Preserves tables/history. Each numbered upgrade is transactional; stop and share any error.\n\n';
const contents = await Promise.all(files.map(name => readFile(new URL(`../supabase/migrations/${name}`, import.meta.url), 'utf8')));
const bundle = header + contents.map((sql, index) => `-- SOURCE: ${files[index]}\n${sql.trimEnd()}\n`).join('\n');
const output = new URL('../supabase/setup_after_001.sql', import.meta.url);
if (process.argv.includes('--check')) {
  if (await readFile(output, 'utf8') !== bundle) throw new Error('Owner SQL bundle is stale; regenerate with npm run prepare:owner-sql.');
  console.log('Owner SQL bundle matches migration sources.');
} else {
  await writeFile(output, bundle);
  console.log('Prepared Supabase owner upgrade bundle (002–006); no database connection made.');
}
